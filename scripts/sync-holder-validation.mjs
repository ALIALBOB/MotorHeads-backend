import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.resolve(scriptDir, "..");
const sourceRoot = path.resolve(
  process.env.HOLDER_VALIDATION_SOURCE_ROOT || path.join(backendRoot, "..", "MotorHeads-5555")
);
const outputRoot = path.join(backendRoot, "src", "vendor", "holder-validation", "v1");

const sourceFiles = [
  "src/lib/validate-holder-layout.js",
  "src/lib/resolve-item-autofit.js",
  "src/lib/clamp-item-adjustment.js",
  "src/lib/holder-placement-geometry.js",
  "src/data/item-placement-rules.js",
  "src/data/category-limits.js",
  "src/data/compatibility-rules.js",
  "src/data/placement-overrides.js"
];

function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

function sourceCommit() {
  try {
    return execFileSync("git", ["-C", sourceRoot, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return null;
  }
}

fs.mkdirSync(outputRoot, { recursive: true });
const files = [];
const fingerprint = crypto.createHash("sha256");

for (const relative of sourceFiles) {
  const sourcePath = path.join(sourceRoot, relative);
  if (!fs.existsSync(sourcePath)) {
    throw new Error(`Missing holder validation source: ${sourcePath}`);
  }

  const artifactRelative = relative.replace(/^src[\\/]/, "");
  const destination = path.join(outputRoot, artifactRelative);
  const bytes = fs.readFileSync(sourcePath);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, bytes);

  const digest = sha256(bytes);
  files.push({ source: relative.replaceAll("\\", "/"), artifact: artifactRelative.replaceAll("\\", "/"), sha256: digest });
  fingerprint.update(artifactRelative.replaceAll("\\", "/"));
  fingerprint.update("\0");
  fingerprint.update(bytes);
  fingerprint.update("\0");
}

const manifest = {
  package: "@motorheads/holder-validation",
  validationVersion: 1,
  catalogVersion: 1,
  placementManifestVersion: 1,
  generatedAt: new Date().toISOString(),
  sourceRoot: "MotorHeads-5555",
  sourceCommit: sourceCommit(),
  artifactSha256: fingerprint.digest("hex"),
  files
};

fs.writeFileSync(
  path.join(outputRoot, "artifact.json"),
  `${JSON.stringify(manifest, null, 2)}\n`,
  "utf8"
);

fs.writeFileSync(
  path.join(outputRoot, "artifact-info.js"),
  `// Generated by scripts/sync-holder-validation.mjs. Do not edit.\n` +
    `export const HOLDER_VALIDATION_ARTIFACT = Object.freeze(${JSON.stringify({
      package: manifest.package,
      validationVersion: manifest.validationVersion,
      catalogVersion: manifest.catalogVersion,
      placementManifestVersion: manifest.placementManifestVersion,
      sourceCommit: manifest.sourceCommit,
      artifactSha256: manifest.artifactSha256
    })});\n`,
  "utf8"
);

console.log(JSON.stringify({ outputRoot, sourceCommit: manifest.sourceCommit, artifactSha256: manifest.artifactSha256, files: files.length }));
